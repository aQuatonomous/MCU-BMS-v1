#!/usr/bin/env python3
"""Turn config/bms_settings.csv + config/bms_options.csv into Inc/bms_config_generated.h (compiled into the firmware).

Guard rails (the generator refuses, or demands an explicit acknowledgement, for risky registers):
  * only data-memory addresses 0x9200-0x93FF; 1- or 2-byte values; no duplicates; at most 32 settings
  * NEVER allowed: the security block 0x9256-0x925E (keys / security settings)
  * fuse / permanent-failure related registers need the text FUSE-OK in the 'ack' column:
      0x9231-0x9233 (fuse), 0x925F (Protection Configuration, holds PF_FUSE), 0x92C0-0x92C3 (Enabled PF A-D), 0x92CB-0x92DF (SOV/SUV/... thresholds)
Usage: python3 tools/gen_config.py            (then rebuild + flash: python3 tools/bms.py flash)
"""
import csv, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SET = os.path.join(ROOT, "config", "bms_settings.csv")
OPT = os.path.join(ROOT, "config", "bms_options.csv")
OUT = os.path.join(ROOT, "Inc", "bms_config_generated.h")
FORBIDDEN = [(0x9256, 0x925E, "security keys / security settings")]
NEEDS_ACK = [(0x9231, 0x9233, "fuse"), (0x925F, 0x925F, "Protection Configuration (PF_FUSE)"), (0x92C0, 0x92C3, "Enabled PF A-D"),
             (0x92CB, 0x92DF, "permanent-fail thresholds")]


def num(s, what):
    try: return int(str(s).strip(), 0)
    except ValueError: sys.exit(f"ERROR: {what}: '{s}' is not a number (use decimal or 0x hex)")


def main():
    items, seen = [], set()
    for ln, r in enumerate(csv.DictReader(open(SET, newline="")), start=2):
        if not r.get("name") or not str(r.get("enabled", "")).strip(): continue
        if str(r["enabled"]).strip() != "1": continue
        where = f"{SET} line {ln} ({r['name']})"
        a, nb, v = num(r["address"], where), num(r["bytes"], where), num(r["value"], where)
        if not 0x9200 <= a <= 0x93FF: sys.exit(f"ERROR: {where}: address 0x{a:04X} is outside the allowed data-memory range 0x9200-0x93FF")
        for lo, hi, why in FORBIDDEN:
            if lo <= a <= hi: sys.exit(f"ERROR: {where}: 0x{a:04X} is FORBIDDEN ({why})")
        for lo, hi, why in NEEDS_ACK:
            if lo <= a <= hi and (r.get("ack") or "").strip() != "FUSE-OK":
                sys.exit(f"ERROR: {where}: 0x{a:04X} is a {why} register. If you really mean to change it, put FUSE-OK in the 'ack' column.")
        if nb not in (1, 2): sys.exit(f"ERROR: {where}: bytes must be 1 or 2")
        if not 0 <= v < (1 << (8 * nb)): sys.exit(f"ERROR: {where}: value {v} does not fit in {nb} byte(s)")
        if a in seen: sys.exit(f"ERROR: {where}: address 0x{a:04X} listed twice")
        seen.add(a); items.append((a, nb, v, r["name"].strip(), (r.get("meaning") or "").strip()))
    if len(items) > 32: sys.exit("ERROR: at most 32 settings are supported")
    opt = {}
    for r in csv.DictReader(open(OPT, newline="")):
        if r.get("name"): opt[r["name"].strip()] = num(r["value"], f"{OPT} {r['name']}")
    for k, lo, hi in (("autoconfig_enabled", 0, 1), ("first_run_delay_s", 1, 30), ("check_period_s", 1, 30), ("keep_awake_period_s", 0, 30)):
        if k not in opt: sys.exit(f"ERROR: {OPT}: missing option '{k}'")
        if not lo <= opt[k] <= hi: sys.exit(f"ERROR: {OPT}: {k} must be {lo}-{hi}")
    L = ["/* GENERATED by tools/gen_config.py from config/bms_settings.csv and config/bms_options.csv.",
         " * DO NOT EDIT BY HAND - edit the CSV files, run the generator, rebuild and flash. */",
         "#ifndef BMS_CONFIG_GENERATED_H", "#define BMS_CONFIG_GENERATED_H", "",
         f"#define BMS_CFG_COUNT                 {len(items)}U",
         f"#define BMS_CFG_AUTOCONFIG_ENABLED    {opt['autoconfig_enabled']}U",
         f"#define BMS_CFG_FIRST_RUN_DELAY_S     {opt['first_run_delay_s']}U",
         f"#define BMS_CFG_CHECK_PERIOD_S        {opt['check_period_s']}U",
         f"#define BMS_CFG_KEEP_AWAKE_PERIOD_S   {opt['keep_awake_period_s']}U", "",
         "/* {data-memory address, bytes, value} */", "static const struct { uint16_t addr; uint8_t nbytes; uint16_t value; } k_bms_cfg[BMS_CFG_COUNT] = {"]
    for i, (a, nb, v, n, m) in enumerate(items):
        L.append(f"    {{ 0x{a:04X}, {nb}, 0x{v:0{2*nb}X} }}{',' if i < len(items) - 1 else ''}   /* {n}: {m} */".replace("*/ */", "*/"))
    L += ["};", "", "#endif /* BMS_CONFIG_GENERATED_H */", ""]
    open(OUT, "w").write("\n".join(L))
    print(f"wrote {os.path.relpath(OUT, ROOT)}: {len(items)} settings, options {opt}")
    for a, nb, v, n, m in items: print(f"  0x{a:04X} {nb}B = 0x{v:0{2*nb}X} ({v:>5})  {n}")


if __name__ == "__main__":
    main()
